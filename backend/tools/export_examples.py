def main() -> int:
    target = BACKEND_ROOT / "docs" / "examples"
    target.mkdir(parents=True, exist_ok=True)

    with TestClient(app) as client:
        index: list[dict] = []
        for name, path, payload in CASES:
            response = client.post(path, json=payload)
            body = response.json()
            (target / f"{name}.json").write_text(
                json.dumps(
                    {"request": {"method": "POST", "path": path, "body": payload},
                     "status": response.status_code,
                     "response": body},
                    indent=2,
                    ensure_ascii=False,
                )
                + "\n",
                encoding="utf-8",
            )
            index.append({"name": name, "path": path, "status": response.status_code})
            print(f"  {name}: {path} -> HTTP {response.status_code}", flush=True)

        (target / "index.json").write_text(
            json.dumps(index, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )

    print(f"\nwrote {len(CASES)} examples to {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
